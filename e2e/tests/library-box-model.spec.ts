test('box controls edit the actual shared button, preserve draft data and cancel a scrub without saving', async ({page}) => {
  await page.goto('/e2e/fixtures/library-box-model.html');
  const frame = page.frameLocator('iframe').first();
  const first = frame.locator('ds-button').first();
  await expect(first.locator('button')).toBeVisible();
  const padding = page.getByRole('spinbutton',{name:'Padding right',exact:true});
  await expect(padding).toHaveValue('4');
  await expect(page.locator('.box-model__content')).not.toHaveText('0×0');
  await padding.fill('20');
  await expect.poll(() => first.locator('button').evaluate(el => getComputedStyle(el).paddingRight)).toBe('20px');
  const border = page.getByRole('spinbutton',{name:'Border top',exact:true});
  await padding.focus(); await page.keyboard.press('ArrowLeft'); await expect(padding).toHaveValue('20');
  await page.keyboard.press('ArrowUp'); await expect(padding).toHaveValue('24');
  await page.keyboard.press('ArrowDown'); await expect(padding).toHaveValue('20');
  await border.fill('2');
  await expect.poll(() => first.locator('button').evaluate(el => getComputedStyle(el).borderTopWidth)).toBe('2px');
  const radius = page.getByRole('spinbutton',{name:'Border radius top-left',exact:true});
  await radius.fill('8');
  await expect.poll(() => first.locator('button').evaluate(el => getComputedStyle(el).borderTopLeftRadius)).toBe('8px');
  const margin = page.getByRole('spinbutton',{name:'Margin left',exact:true});
  await margin.fill('10');
  await expect.poll(() => first.evaluate(el => getComputedStyle(el).marginLeft)).toBe('10px');
  const saved = await page.locator('#saved-draft').textContent();
  const data = JSON.parse(saved!); expect(data.config).toEqual({schema:1,brand:'preserved'});expect(data.css).toContain('.brand { color: var(--brand); }');
  await padding.focus(); const bounds=(await padding.boundingBox())!;
  await page.mouse.move(bounds.x+5,bounds.y+5);await page.mouse.down();await page.mouse.move(bounds.x+35,bounds.y+5);
  await expect(padding).not.toHaveValue('20');
  await page.keyboard.press('Escape');await page.mouse.up();
  await expect(padding).toHaveValue('20');
  await expect(page.locator('#saved-draft')).toHaveText(saved!);
  await expect.poll(() => first.locator('button').evaluate(el => getComputedStyle(el).paddingRight)).toBe('20px');
});
