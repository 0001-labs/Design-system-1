/** Copy the shared component dependency graph; consumers never edit the snapshot. */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const source = fileURLToPath(new URL('../DS1/', import.meta.url));
const args = process.argv.slice(2);
const option = name => args[args.indexOf(name) + 1];
if (!args.includes('--target') || !args.includes('--components')) {
  throw new Error('Usage: node scripts/sync-components.mjs --target <directory> --components button,text,… [--check]');
}
const target = resolve(option('--target'));
if (target === resolve(source) || source.startsWith(target + '/') || target.startsWith(source)) throw new Error('The target must be a consumer snapshot.');
const components = [...new Set(option('--components').split(','))].sort();
const files = new Map();

function visit(file) {
  const path = resolve(source, file);
  if (!path.startsWith(source)) throw new Error(`Dependency outside DS1: ${file}`);
  if (files.has(file)) return;
  const content = readFileSync(path, 'utf8');
  files.set(file, content);
  if (!/\.(ts|css)$/.test(file)) return;
  const imports = /(?:\bfrom\s*|\bimport\s*\(\s*|^\s*import\s*|@import\s*)["'](\.[^"']+)["']/gm;
  for (const match of content.matchAll(imports)) {
    const base = resolve(dirname(path), match[1].split('?')[0]);
    const dependency = [base, `${base}.ts`, `${base}.json`, join(base, 'index.ts')].find(existsSync);
    if (!dependency) throw new Error(`Unresolved ${match[1]} in ${file}`);
    visit(relative(source, dependency));
  }
}

const entries = components.map(name => {
  if (!/^[a-z][a-z-]*$/.test(name)) throw new Error(`Invalid component: ${name}`);
  const file = ['2-core', '3-unit', '4-page'].map(layer => `${layer}/ds-${name}.ts`).find(file => existsSync(join(source, file)));
  if (!file) throw new Error(`Unknown component: ${name}`);
  visit(file);
  return file;
});
// React consumers may import the optional, source-owned state adapter.
if (components.includes('button')) visit('react/button.ts');
if (components.includes('split')) visit('react/split.ts');
if (components.includes('composer')) visit('react/composer.ts');
if (components.includes('menu')) visit('react/menu.ts');
if (components.includes('accordion')) visit('react/accordion.ts');
if (['checkbox', 'switch', 'select', 'color'].some(name => components.includes(name))) visit('react/choice.ts');
if (components.includes('dialog')) visit('react/dialog.ts');
if (components.includes('swatch')) visit('0-face/tooltips.ts');
if (components.includes('input') || components.includes('textarea')) visit('react/input.ts');
visit('1-root/component-tokens.css');
visit('1-root/controls.css');
files.set('components.ts', '/** Generated by Design system 1. Change the source and sync. */\n' + entries.map(file => `export * from './${file.slice(0, -3)}';\n`).join(''));
const sha = content => createHash('sha256').update(content).digest('hex');
const hashes = Object.fromEntries([...files].sort(([a], [b]) => a.localeCompare(b)).map(([file, content]) => [file, sha(content)]));
const manifestPath = join(target, 'components-manifest.json');
const previous = existsSync(manifestPath) ? JSON.parse(readFileSync(manifestPath, 'utf8')) : null;
const changed = [...files].filter(([file, content]) => !existsSync(join(target, file)) || readFileSync(join(target, file), 'utf8') !== content).map(([file]) => file);
const removed = Object.keys(previous?.files ?? {}).filter(file => !files.has(file));
if (args.includes('--check')) {
  if (changed.length || removed.length || JSON.stringify(previous?.files) !== JSON.stringify(hashes)) {
    throw new Error(`Component snapshot differs: ${[...changed, ...removed].join(', ') || 'manifest'}`);
  }
  console.log(`Verified ${components.length} shared components (${files.size} files) in ${target}`);
} else {
  for (const file of removed) {
    const path = resolve(target, file);
    if (!path.startsWith(target + '/')) throw new Error(`Invalid old manifest path: ${file}`);
    rmSync(path, { force: true });
  }
  for (const [file, content] of files) {
    const path = join(target, file);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
  const commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: source, encoding: 'utf8' }).trim();
  writeFileSync(manifestPath, JSON.stringify({ source: 'Design system 1/DS1', commit, components, files: hashes }, null, 2) + '\n');
  console.log(`Synced ${components.length} shared components (${files.size} files) into ${target}`);
}
