/**
 * Generate icon map from SVG files in DS1/x-icon/
 *
 * This script reads all SVG files and generates a TypeScript module
 * that exports a static map of icon names to SVG strings.
 *
 * Run: vp run generate:icons
 */

import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from "fs";
import { join, basename, dirname } from "path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const ICONS_DIR = join(scriptDir, "..", "DS1", "x-icon");
const OUTPUT_DIR = join(scriptDir, "..", "DS1", "2-core", "generated");
const OUTPUT_FILE = join(OUTPUT_DIR, "ds-icon-map.ts");

const immediate = new Set<string>([
  'app',
  'plus',
  'loop',
  'template',
  'pad',
  'pen',
  'bag',
  'apple',
  'google',
  'lists',
  'shared',
  'calendar',
  'store',
  'archive',
  'stats',
  'camera',
  'views',
  'search',
  'home',
  'folder',
  'close',
  'left',
  'right',
  'up',
  'down',
  'sup',
  'sdown',
  'expand',
  'collapse',
  'check',
  'more',
  'lock',
  'unlock',
  'mic',
  'unmic',
  'compose',
  'note',
  'email',
  'see',
  'unsee',
  'star',
  'unstar',
  'open',
  'delete',
  'duplicate',
])

function generateIconMap() {
  // Ensure output directory exists
  if (!existsSync(OUTPUT_DIR)) {
    mkdirSync(OUTPUT_DIR, { recursive: true });
  }

  // Read all SVG files
  const svgFiles = readdirSync(ICONS_DIR).filter((file) =>
    file.toLowerCase().endsWith(".svg")
  );

  // Build the map
  const iconMap: Record<string, string> = {};

  for (const file of svgFiles) {
    const filePath = join(ICONS_DIR, file);
    const iconName = basename(file, ".svg").toLowerCase();
    const svgContent = readFileSync(filePath, "utf-8").trim();
    iconMap[iconName] = svgContent;
  }

  // Sort keys for consistent output
  const sortedKeys = Object.keys(iconMap).sort();

  // Generate TypeScript content
  const tsContent = `/**
 * Auto-generated icon map - DO NOT EDIT
 * Generated by: vp run scripts/generate-icons.ts
 * Source: DS1/x-icon/*.svg
 */

export const iconNameToSvgMap = {
${sortedKeys.map((key) => `  "${key}": ${JSON.stringify(iconMap[key])},`).join("\n")}
} as const;

export type IconName = keyof typeof iconNameToSvgMap;

export const iconNames = [
${sortedKeys.map((key) => `  "${key}",`).join("\n")}
] as const;
`;

  writeFileSync(OUTPUT_FILE, tsContent, "utf-8");
  for (const name of immediate) {
    if (!iconMap[name]) throw new Error(`Unknown immediate icon: ${name}`);
  }
  for (const [part, include] of [['immediate', true], ['extra', false]] as const) {
    const icons = Object.fromEntries(sortedKeys.filter(name => immediate.has(name) === include).map(name => [name, iconMap[name]]));
    const content = '// Generated by scripts/generate-icons.ts from DS1/x-icon.\nexport const icons: Readonly<Record<string, string>> = ' + JSON.stringify(icons, null, 2) + '\n' +
      (include ? 'export const deferredIconNames = ' + JSON.stringify(sortedKeys.filter(name => !immediate.has(name))) + ' as const\n' : '');
    writeFileSync(join(OUTPUT_DIR, `icons-${part}.ts`), content, 'utf8');
  }


  console.log(`✓ Generated ${OUTPUT_FILE}`);
  console.log(`  ${sortedKeys.length} icons: ${sortedKeys.join(", ")}`);
}

generateIconMap();

