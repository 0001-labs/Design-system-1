/** Keep the portable arrow stylesheet and both typography entry points self-contained. */
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../../DS1/1-root/', import.meta.url);
const bytes = readFileSync(new URL('fonts/Inter-Arrows.woff2', root));
const sheet = `/* inter-arrows:start — generated by scripts/fonts/embed-arrows.mjs */
/* Inter 4.1, SIL Open Font License 1.1; see fonts/Inter-LICENSE.md. */
@font-face {
  font-family: "Inter Arrows";
  src: url("data:font/woff2;base64,${bytes.toString('base64')}") format("woff2");
  unicode-range: U+2190-21FF, U+27F0-27FF, U+2900-297F, U+2B00-2BFF;
  font-weight: 100 900;
  font-style: normal;
  font-display: swap;
}
/* inter-arrows:end */`;
for (const file of ['inter-arrows.css', 'fonts.css', 'component-tokens.css']) {
  const url = new URL(file, root);
  const before = readFileSync(url, 'utf8');
  const after = file === 'inter-arrows.css' ? `${sheet}\n` : before.replace(/\/\* inter-arrows:start[\s\S]*?\/\* inter-arrows:end \*\//, sheet);
  if (process.argv.includes('--check')) {
    if (after !== before) throw new Error(`${file}: run node scripts/fonts/embed-arrows.mjs`);
  } else writeFileSync(url, after);
}
